import type { Locale } from "@/lib/i18n/dictionaries";

/**
 * The 360° heads in the gallery. Each one is a turntable: `frames` WebP images of
 * one full turn (frame 00 faces the camera), made by `scripts/head-frames.mjs` at
 *   `${base}/720/NN.webp` and `${base}/1440/NN.webp`  (NN = 00, 01, … frames - 1)
 *
 * To add a head: run the script on its orbit video, then list it here. The page shows
 * only heads whose first frame exists on disk, in this order, so entries can wait here
 * before their frames are made. `placeholder` heads (the test sequence) are shown only
 * while no real head is ready.
 */
export type Head = {
  id: string;
  name: Record<Locale, string>;
  frames: number;
  base: string;
  /** Size of the 1440 frames, in px. The stage keeps this aspect ratio. */
  width: number;
  height: number;
  /** Color at the edges of the frames; the stage uses it so the frame dissolves into it. */
  backdrop?: string;
  placeholder?: boolean;
};

/** The widths the frames are saved at. The viewer picks one by stage width × devicePixelRatio. */
export const HEAD_SIZES = [720, 1440] as const;

export const frameUrl = (head: Head, size: number, index: number) =>
  `${head.base}/${size}/${String(index).padStart(2, "0")}.webp`;

/** Real frames are square: 1440×1440 (and 720×720), 72 per turn. */
const square = { frames: 72, width: 1440, height: 1440, backdrop: "#0d0e10" };

const real = (id: string, en: string, es: string): Head => ({
  id,
  name: { en, es },
  base: `/landing/heads/${id}`,
  ...square,
});

